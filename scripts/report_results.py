"""Render saved measurements into Markdown without rerunning GPU work."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", type=Path, nargs="*")
    parser.add_argument("--output", type=Path, default=ROOT / "results/SUMMARY.md")
    args = parser.parse_args()
    paths = args.inputs or sorted((ROOT / "results").glob("*.json"))
    if not paths:
        parser.error("no result JSON found")
    lines = [
        "# Saved benchmark results",
        "",
        "Generated by `scripts/report_results.py`.",
        "",
        "Ratios use the PyTorch eager median in the same case. Greater than 1 is faster.",
        "Different dtypes and timing modes are separate experiments. See",
        "[methodology](../docs/BENCHMARKING.md) for limitations.",
        "",
    ]
    for path in paths:
        report = json.loads(path.read_text(encoding="utf-8"))
        if "variants" not in report and "cases" not in report:
            print(f"Skipping {path.name}: not a benchmark report")
            continue
        lines.extend([f"## {path.name}", ""])
        if "cases" not in report:
            lines.extend(
                [
                    f"{report['gpu']}; {report['dtype']}; {report['timing']}.",
                    "",
                    "| CUDA variant | Median (us) |",
                    "| --- | ---: |",
                ]
            )
            for name, result in report["variants"].items():
                lines.append(f"| {name} | {result['median_ms'] * 1000:.3f} |")
        else:
            lines.extend(
                [
                    f"{report['environment']['gpu']}; timing: {report['settings']['timing']}; "
                    f"cache: {report['settings'].get('cache', 'warm')}; "
                    f"UTC: {report['timestamp_utc']}.",
                    "",
                    "| Op | Shape | Dtype | Variant | Median (us) | Speedup | Max abs error |",
                    "| --- | --- | --- | --- | ---: | ---: | ---: |",
                ]
            )
            for case in report["cases"]:
                shape = " x ".join(map(str, case["shape"]))
                for name, result in case["variants"].items():
                    lines.append(
                        f"| {case['op']} | {shape} | {case['dtype']} | {name} | "
                        f"{result['median_ms'] * 1000:.3f} | "
                        f"{result['speedup_vs_torch']:.2f}x | "
                        f"{result['max_abs_error']:.3g} |"
                    )
        lines.append("")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Saved {args.output}")


if __name__ == "__main__":
    main()
